import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = (...segments) => fs.readFileSync(path.join(root, 'source', 'src', ...segments), 'utf8')
const sessions = read('domain', 'sessions', 'persistence.ts')
const exports = read('domain', 'export', 'artifacts.ts')
const main = read('app', 'bootstrap.ts')
assert.match(sessions, /SESSION_SCHEMA_VERSION = 5/)
assert.match(sessions, /fit\.transformModel \?\?= 'rigid'/)
assert.match(sessions, /fit\.landmarkWarp \?\?= null/)
assert.match(sessions, /fit\.deformation \?\?= null/)
assert.match(sessions, /fit\.linearDiagnostics \?\?=/)
assert.match(sessions, /fit\.reflectionConfirmed \?\?= false/)
assert.match(exports, /transform_model: fit\.transformModel/)
assert.match(exports, /nonlinear_landmark_warp: fit\.landmarkWarp/)
assert.match(exports, /automatic_deformation_grid: fit\.deformation/)
assert.match(exports, /reflection: fit\.linearDiagnostics\.reflected/)
assert.match(exports, /linear_warnings: fit\.linearDiagnostics\.warnings/)
assert.match(sessions, /payload\.savedAt \?\? payload\.saved_at/)
assert.match(sessions, /payload\.appVersion \?\? payload\.version/)
assert.match(sessions, /schemaVersion > SESSION_SCHEMA_VERSION/)
assert.match(sessions, /geometryDifference/)
assert.match(exports, /createRegistrationArtifacts/)
assert.match(exports, /saveArtifacts/)
assert.match(exports, /await saveArtifact/)
assert.match(main, /createSessionPayload/)
assert.match(main, /parseSessionPayload/)
assert.match(main, /sessionGeometryMismatches/)
assert.match(main, /createRegistrationArtifacts/)
assert.doesNotMatch(main, /version:'0\.7\.0'/)
assert.doesNotMatch(main, /saved_at:/)
console.log('session schema, migration, and export artifact checks passed')
